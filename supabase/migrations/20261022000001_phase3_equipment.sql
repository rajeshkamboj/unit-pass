-- =============================================================================
-- UnitPass — Phase 3: equipment, permanent public tokens, public UnitPass RPC
-- =============================================================================
-- Idempotent and non-destructive. Safe on an empty project AND on a project
-- where `supabase/legacy/schema.sql.txt` created `equipment`/its enums before.
-- Existing rows are preserved; only missing columns are added and NULL
-- `public_token` values are backfilled (once). No column or row is deleted.
--
-- Apply after the Phase 1 and Phase 2 migrations:
--   psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -f supabase/migrations/20261022000001_phase3_equipment.sql
--
-- Security model
--  * `equipment.public_token` is the ONLY anonymous-facing identifier. It is
--    generated by the database (122 random bits), is unique, and is made
--    immutable by a trigger so no future code path can invalidate a printed QR.
--  * Anonymous visitors get no table privileges at all. The single public read
--    surface is `public.get_public_unitpass(uuid)`, a SECURITY DEFINER function
--    that returns an explicit whitelist (no internal ids, no installer notes, no
--    customer PII). Never `select *` the table and hide fields in the UI.
--  * Tenant writes go through RLS (`is_company_member(company_id)`) plus a
--    trigger that refuses a `customer_id` belonging to another company.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 0. Extensions: gen_random_uuid() is core in PostgreSQL 13+ (Supabase 15+).
-- -----------------------------------------------------------------------------
do $$
begin
  create extension if not exists pgcrypto;
exception
  when others then
    raise notice 'Skipping pgcrypto (%). gen_random_uuid() comes from PostgreSQL core.', sqlerrm;
end
$$;

-- -----------------------------------------------------------------------------
-- 1. Enums (reuse the legacy spellings; never invent new labels)
-- -----------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'equipment_type' and n.nspname = 'public'
  ) then
    create type public.equipment_type as enum (
      'Air Conditioner', 'Furnace', 'Heat Pump', 'Mini Split', 'Boiler', 'Air Handler', 'Other'
    );
  else
    -- A legacy/partial install may predate a label. ADD VALUE is idempotent and
    -- the labels are not used by DML in this migration.
    alter type public.equipment_type add value if not exists 'Air Conditioner';
    alter type public.equipment_type add value if not exists 'Furnace';
    alter type public.equipment_type add value if not exists 'Heat Pump';
    alter type public.equipment_type add value if not exists 'Mini Split';
    alter type public.equipment_type add value if not exists 'Boiler';
    alter type public.equipment_type add value if not exists 'Air Handler';
    alter type public.equipment_type add value if not exists 'Other';
  end if;

  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'equipment_status' and n.nspname = 'public'
  ) then
    create type public.equipment_status as enum ('Active', 'Inactive', 'Replaced');
  else
    alter type public.equipment_status add value if not exists 'Active';
    alter type public.equipment_status add value if not exists 'Inactive';
    alter type public.equipment_status add value if not exists 'Replaced';
  end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 2. Equipment table
-- -----------------------------------------------------------------------------
create table if not exists public.equipment (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies (id) on delete cascade,
  customer_id uuid not null references public.customers (id) on delete cascade,
  equipment_name text not null,
  equipment_type public.equipment_type not null,
  manufacturer text,
  model_number text,
  serial_number text,
  installation_date date,
  warranty_expiration_date date,
  warranty_notes text,
  next_service_date date,
  service_interval integer,
  installer_notes text,
  public_notes text,
  equipment_photo_url text,
  equipment_photo_path text,
  status public.equipment_status not null default 'Active',
  public_token uuid not null default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Converge a legacy/partial table without touching existing data.
alter table public.equipment add column if not exists company_id uuid;
alter table public.equipment add column if not exists customer_id uuid;
alter table public.equipment add column if not exists equipment_name text;
alter table public.equipment add column if not exists equipment_type public.equipment_type;
alter table public.equipment add column if not exists manufacturer text;
alter table public.equipment add column if not exists model_number text;
alter table public.equipment add column if not exists serial_number text;
alter table public.equipment add column if not exists installation_date date;
alter table public.equipment add column if not exists warranty_expiration_date date;
alter table public.equipment add column if not exists warranty_notes text;
alter table public.equipment add column if not exists next_service_date date;
alter table public.equipment add column if not exists service_interval integer;
alter table public.equipment add column if not exists installer_notes text;
alter table public.equipment add column if not exists public_notes text;
-- Legacy column, intentionally kept and unused (deprecated in Phase 3).
alter table public.equipment add column if not exists equipment_photo_url text;
-- Phase 3 photo upload is deferred; the path column exists for the public RPC
-- contract and for the phase that implements private photos.
alter table public.equipment add column if not exists equipment_photo_path text;
alter table public.equipment add column if not exists status public.equipment_status;
alter table public.equipment add column if not exists public_token uuid;
alter table public.equipment add column if not exists created_at timestamptz;
alter table public.equipment add column if not exists updated_at timestamptz;

-- Backfill only what is genuinely missing; never rewrite existing values.
update public.equipment set status = 'Active' where status is null;
update public.equipment set public_token = gen_random_uuid() where public_token is null;
update public.equipment set created_at = now() where created_at is null;
update public.equipment set updated_at = now() where updated_at is null;

alter table public.equipment alter column status set default 'Active';
alter table public.equipment alter column status set not null;
alter table public.equipment alter column public_token set default gen_random_uuid();
alter table public.equipment alter column public_token set not null;
alter table public.equipment alter column created_at set default now();
alter table public.equipment alter column created_at set not null;
alter table public.equipment alter column updated_at set default now();
alter table public.equipment alter column updated_at set not null;

-- NOT NULL on the identity columns only when the legacy data allows it, so this
-- migration can never fail on (or destroy) pre-existing rows.
do $$
begin
  if not exists (select 1 from public.equipment where company_id is null) then
    alter table public.equipment alter column company_id set not null;
  end if;
  if not exists (select 1 from public.equipment where customer_id is null) then
    alter table public.equipment alter column customer_id set not null;
  end if;
  if not exists (select 1 from public.equipment where equipment_name is null) then
    alter table public.equipment alter column equipment_name set not null;
  end if;
  if not exists (select 1 from public.equipment where equipment_type is null) then
    alter table public.equipment alter column equipment_type set not null;
  end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 3. Timestamps + public-token immutability
-- -----------------------------------------------------------------------------
drop trigger if exists equipment_set_updated_at on public.equipment;
create trigger equipment_set_updated_at
  before update on public.equipment
  for each row execute function public.set_updated_at();

-- A printed QR must keep working forever. Any attempt to change the token —
-- from an app bug, a SQL console, or a future feature — fails loudly.
create or replace function public.prevent_public_token_change()
returns trigger
language plpgsql
as $$
begin
  if old.public_token is distinct from new.public_token then
    raise exception 'public_token is immutable' using errcode = '23514';
  end if;
  return new;
end
$$;

drop trigger if exists equipment_public_token_immutable on public.equipment;
create trigger equipment_public_token_immutable
  before update on public.equipment
  for each row execute function public.prevent_public_token_change();

revoke all on function public.prevent_public_token_change() from public;

-- -----------------------------------------------------------------------------
-- 4. Tenant integrity: the customer must belong to the same company
-- -----------------------------------------------------------------------------
-- RLS already blocks forging `company_id`; this trigger also blocks pairing the
-- caller's company with another tenant's customer. It runs with invoker rights,
-- so the customer lookup itself is RLS-scoped (Company B's rows are invisible).
create or replace function public.equipment_customer_same_company()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1
    from public.customers c
    where c.id = new.customer_id
      and c.company_id = new.company_id
  ) then
    raise exception 'equipment.customer_id must belong to the same company'
      using errcode = '23514';
  end if;
  return new;
end
$$;

drop trigger if exists equipment_customer_same_company on public.equipment;
create trigger equipment_customer_same_company
  before insert or update of customer_id, company_id on public.equipment
  for each row execute function public.equipment_customer_same_company();

revoke all on function public.equipment_customer_same_company() from public;

-- -----------------------------------------------------------------------------
-- 5. Indexes
-- -----------------------------------------------------------------------------
create unique index if not exists equipment_public_token_key
  on public.equipment (public_token);
create index if not exists equipment_company_status_idx
  on public.equipment (company_id, status);
create index if not exists equipment_company_customer_idx
  on public.equipment (company_id, customer_id);
create index if not exists equipment_company_next_service_idx
  on public.equipment (company_id, next_service_date);

-- -----------------------------------------------------------------------------
-- 6. Row Level Security
-- -----------------------------------------------------------------------------
alter table public.equipment enable row level security;

-- Legacy recursive policies (they queried company_members from a policy on a
-- table that is itself referenced) and any earlier Phase 3 run.
drop policy if exists "Members can view equipment of their company" on public.equipment;
drop policy if exists "Members can insert equipment for their company" on public.equipment;
drop policy if exists "Members can update equipment of their company" on public.equipment;
drop policy if exists "Members can delete equipment of their company" on public.equipment;
drop policy if exists equipment_select_company_members on public.equipment;
drop policy if exists equipment_insert_company_members on public.equipment;
drop policy if exists equipment_update_company_members on public.equipment;
drop policy if exists equipment_delete_company_members on public.equipment;

create policy equipment_select_company_members
  on public.equipment for select
  to authenticated
  using (public.is_company_member(company_id));

create policy equipment_insert_company_members
  on public.equipment for insert
  to authenticated
  with check (public.is_company_member(company_id));

create policy equipment_update_company_members
  on public.equipment for update
  to authenticated
  using (public.is_company_member(company_id))
  with check (public.is_company_member(company_id));

-- No delete policy on purpose: equipment is retired with status = 'Replaced'
-- so the printed QR keeps resolving. The privilege is not granted either.
-- (A tenant owner can still purge explicitly via SQL/service_role if ever needed.)

revoke all on public.equipment from anon;
grant select, insert, update on public.equipment to authenticated;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant all on public.equipment to service_role;
  end if;
end
$$;

-- -----------------------------------------------------------------------------
-- 7. The only anonymous read surface: an explicit public whitelist
-- -----------------------------------------------------------------------------
-- Returns exactly the approved public fields. No equipment/customer/company ids,
-- no installer_notes, no customer PII, no billing/reminder data.
-- Unknown tokens return SQL NULL (the page renders a generic 404).
create or replace function public.get_public_unitpass(p_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'company', jsonb_build_object(
      'name', c.name,
      'phone', c.phone,
      'email', c.email,
      'website', c.website,
      'service_booking_url', c.service_booking_url,
      'logo_url', c.logo_url
    ),
    'equipment', jsonb_build_object(
      'name', e.equipment_name,
      'type', e.equipment_type,
      'manufacturer', e.manufacturer,
      'model_number', e.model_number,
      'serial_number', e.serial_number,
      'installation_date', e.installation_date,
      'warranty_expiration_date', e.warranty_expiration_date,
      'warranty_notes', e.warranty_notes,
      'public_notes', e.public_notes,
      'status', e.status,
      'photo_path', e.equipment_photo_path
    )
  )
  from public.equipment e
  join public.companies c on c.id = e.company_id
  where e.public_token = p_token;
$$;

revoke all on function public.get_public_unitpass(uuid) from public;
grant execute on function public.get_public_unitpass(uuid) to anon, authenticated;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant execute on function public.get_public_unitpass(uuid) to service_role;
  end if;
end
$$;

commit;

